/** 一个提问里最多命中几个话题，避免上下文过长 */
const TOPIC_LIMIT = 2

/** 月龄命中的分段；生日缺失/非法时返回 null */
export function stageGuideFor(totalMonths) {
  const value = Number(totalMonths)
  if (!Number.isFinite(value) || value < 0) return null
  return AGE_STAGE_GUIDE.find((item) => value < item.maxMonths) || null
}

/**
 * 按提问里的关键词命中话题。
 * @param {string} question 家长这一轮的提问
 * @param {number} [limit] 最多返回几个
 */
export function matchTopics(question, limit = TOPIC_LIMIT) {
  const text = String(question || '')
  if (!text) return []
  const hit = []
  TOPIC_GUIDE.forEach((topic) => {
    if (hit.length >= limit) return
    if (topic.keywords.some((word) => text.indexOf(word) >= 0)) hit.push(topic)
  })
  return hit
}

/**
 * 拼出发给模型的「通用参考」段：
 * 当前月龄的阶段要点（有生日就带上）+ 提问命中的话题要点。
 * 两块都没有时返回空串，由调用方决定不拼这一段。
 *
 * @param {object} params
 * @param {object} [params.baby] 宝宝档案，用 birthday 算月龄
 * @param {string} [params.question] 这一轮的提问
 * @param {string|Date} [params.now] 参照时刻
 */
export function buildKnowledgeContext({ baby, question, now } = {}) {
  const blocks = []

  const parts = ageParts(baby && baby.birthday, now || new Date())
  const stage = parts ? stageGuideFor(parts.totalMonths) : null
  if (stage) {
    blocks.push(
      [`【月龄阶段参考】当前处于 ${stage.label}，这一阶段的常规做法：`]
        .concat(stage.points.map((point) => `- ${point}`))
        .join('\n'),
    )
  }

  matchTopics(question).forEach((topic) => {
    blocks.push(
      [`【常见问题参考】${topic.title}：`]
        .concat(topic.points.map((point) => `- ${point}`))
        .join('\n'),
    )
  })

  if (!blocks.length) return ''
  return ['以下是通用的育儿参考（不是这个宝宝的记录，回答时要说明是通用建议）：']
    .concat(blocks)
    .join('\n')
}
